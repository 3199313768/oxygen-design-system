import ts from 'typescript';
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
export function loadDocs(base = root) {
  const directory = path.join(base, 'apps/storybook/docs/content');
  const literal = (node) => {
    if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return node.text;
    if (ts.isArrayLiteralExpression(node)) return node.elements.map(literal);
    if (ts.isObjectLiteralExpression(node)) return Object.fromEntries(node.properties.map((prop) => [prop.name.text, literal(prop.initializer)]));
    throw new Error('Documentation data must use string, array or object literals.');
  };
  return readdirSync(directory).filter((file) => file.endsWith('.ts') && file !== 'index.ts').flatMap((file) => {
    const source = ts.createSourceFile(file, readFileSync(path.join(directory, file), 'utf8'), ts.ScriptTarget.Latest, true);
    return source.statements.filter(ts.isVariableStatement).flatMap((statement) => statement.declarationList.declarations.filter((decl) => decl.initializer && ts.isArrayLiteralExpression(decl.initializer)).flatMap((decl) => literal(decl.initializer)));
  });
}

export function storySource(doc, definition) {
  return `// Generated by pnpm docs:generate; edit docs/content, docs/examples or docs/playgrounds.json.\nimport type { Meta, StoryObj } from '@storybook/react-vite';\nimport { Example } from '../../docs/examples/${doc.name}';\nimport source from '../../docs/examples/${doc.name}.tsx?raw';\nimport { componentMeta } from '../../docs/component-meta';\n\nconst meta = {\n  ...componentMeta('${doc.name}', Example, source),\n  id: 'components-${doc.name.toLowerCase()}',\n  title: ${JSON.stringify(`${doc.category === '页面模式' ? '页面模式' : '组件'}/${doc.category}/${doc.name} ${doc.title}`)},\n} satisfies Meta<typeof Example>;\nexport default meta;\ntype Story = StoryObj<typeof meta>;\nexport const Playground: Story = { name: '基础示例与 Playground' };\n${Object.entries(definition.states).map(([label, args], index) => `export const State${index + 1}: Story = { name: ${JSON.stringify(label)}, args: ${JSON.stringify(args)} };`).join('\n')}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const definitions = JSON.parse(readFileSync(path.join(root, 'apps/storybook/docs/playgrounds.json'), 'utf8'));
  const directory = path.join(root, 'apps/storybook/stories/components');
  mkdirSync(directory, { recursive: true });
  for (const doc of loadDocs()) {
    if (!definitions[doc.name]) throw new Error(`Missing Playground: ${doc.name}`);
    writeFileSync(path.join(directory, `${doc.name}.stories.tsx`), storySource(doc, definitions[doc.name]));
  }
  console.log(`Generated ${loadDocs().length} component documentation routes.`);
}
